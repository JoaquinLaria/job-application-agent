"""
The reviewer. Grades a resume and cover letter against GOLD.md before anything
becomes a PDF, and refuses to pass work that breaks a hard rule.

    python review.py --resume <resume.docx> --letter <letter.docx> [--jd jd.txt] [--company "Name"]

Exit code 0 means it passed. Exit code 1 means a hard gate failed and the
documents should not be sent.

Hard gates fail the run. Warnings are printed and do not.
"""
